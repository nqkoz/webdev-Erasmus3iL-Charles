CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  password_hash TEXT,
  role TEXT NOT NULL CHECK (role IN ('student', 'staff')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX users_email_case_insensitive ON users (lower(email));

CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE labs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  location TEXT NOT NULL
);

CREATE TABLE workstations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lab_id INTEGER NOT NULL REFERENCES labs(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  UNIQUE (lab_id, name)
);

CREATE TABLE bookings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  workstation_id INTEGER NOT NULL REFERENCES workstations(id),
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (starts_at < ends_at)
);

CREATE INDEX bookings_user_starts_at ON bookings (user_id, starts_at);
CREATE INDEX bookings_workstation_time ON bookings (workstation_id, starts_at, ends_at);
CREATE INDEX sessions_expires_at ON sessions (expires_at);

CREATE FUNCTION prevent_active_booking_overlap() RETURNS trigger AS $$
BEGIN
  IF NEW.status = 'active' THEN
    PERFORM pg_advisory_xact_lock(NEW.workstation_id::bigint);
    IF EXISTS (
      SELECT 1
      FROM bookings
      WHERE workstation_id = NEW.workstation_id
        AND status = 'active'
        AND starts_at < NEW.ends_at
        AND ends_at > NEW.starts_at
        AND (TG_OP = 'INSERT' OR id <> NEW.id)
    ) THEN
      RAISE EXCEPTION 'workstation booking overlaps an active booking'
        USING ERRCODE = '23P01';
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER bookings_no_active_overlap_insert
BEFORE INSERT ON bookings
FOR EACH ROW EXECUTE FUNCTION prevent_active_booking_overlap();

CREATE TRIGGER bookings_no_active_overlap_update
BEFORE UPDATE OF workstation_id, starts_at, ends_at, status ON bookings
FOR EACH ROW EXECUTE FUNCTION prevent_active_booking_overlap();
